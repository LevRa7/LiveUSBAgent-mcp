def get_locale_bundle(lang: str) -> Dict[str, Any]:
    """Return translation dict for *lang*, falling back to DEFAULT_LANGUAGE."""
    code = (lang or "").strip().lower().split("-")[0]
    return TRANSLATIONS.get(code, TRANSLATIONS[DEFAULT_LANGUAGE])


def get_all_locales() -> Dict[str, Dict[str, Any]]:
    """Return all 7 supported locale dictionaries."""
    return TRANSLATIONS


def get_connect_locales() -> Dict[str, Dict[str, Any]]:
    """Return compact locale subset for the /connect/ MCP instruction page."""
    out: Dict[str, Dict[str, Any]] = {}
    for code, bundle in TRANSLATIONS.items():
        subset: Dict[str, Any] = {"_meta": bundle["_meta"]}
        for k, v in bundle.items():
            if k.startswith("connect_") or k in ("btn_copy", "btn_copied", "lang_button"):
                subset[k] = v
        out[code] = subset
    return out
